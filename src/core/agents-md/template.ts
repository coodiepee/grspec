/**
 * AGENTS.md Template
 *
 * Section templates and code-philosophy summary for AGENTS.md generation.
 * AGENTS.md is the universal project context file read by 20+ AI coding tools.
 */

export interface AgentsMdSections {
  projectName: string;
  projectDescription: string;
  techStack: string;
  commands: string;
  architecture: string;
  codeStyle: string;
  testing: string;
  gitWorkflow: string;
  boundaries: string;
  grspecWorkflow: string;
}

const CODE_STYLE_SUMMARY = `- Names: self-documenting, no generic placeholders (\`data\`, \`info\`, \`tmp\`, \`result\`)
- Functions: one abstraction level per function, describable in one sentence without "and"
- Abstraction: tolerate duplication until the third occurrence before extracting
- Comments: explain WHY (decisions, trade-offs), never WHAT
- Logic: every line justifiable from first principles in current context
- Assumptions: encode preconditions as types, guard clauses, or assertions
- Simplicity: default to the plainest, most conventional approach`;

export function getCodeStyleSummary(): string {
  return CODE_STYLE_SUMMARY;
}

export function assembleAgentsMd(sections: AgentsMdSections, grspecVersion: string): string {
  const lines: string[] = [];

  lines.push(`# ${sections.projectName}`);
  lines.push(`<!-- Generated by grspec v${grspecVersion}. Edit freely. -->`);
  lines.push('');
  if (sections.projectDescription) {
    lines.push(sections.projectDescription);
    lines.push('');
  }
  if (sections.techStack) {
    lines.push(sections.techStack);
    lines.push('');
  }

  lines.push('## Commands');
  lines.push('');
  lines.push(sections.commands);
  lines.push('');

  lines.push('## Architecture');
  lines.push('');
  lines.push(sections.architecture);
  lines.push('');

  lines.push('## Code Style');
  lines.push('');
  lines.push(sections.codeStyle);
  lines.push('');

  lines.push('## Testing');
  lines.push('');
  lines.push(sections.testing);
  lines.push('');

  lines.push('## Git Workflow');
  lines.push('');
  lines.push(sections.gitWorkflow);
  lines.push('');

  lines.push('## Boundaries');
  lines.push('');
  lines.push(sections.boundaries);
  lines.push('');

  lines.push('## grspec Workflow');
  lines.push('');
  lines.push(sections.grspecWorkflow);
  lines.push('');

  return lines.join('\n');
}
